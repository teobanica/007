"""
flatlin.py -- core library for "Flat linearity of uniform groups".

A uniform group is a finite quotient Z_K^{*M} -> Gamma -> Z_K^M, given here
by M generators g_1,...,g_M, as permutations.  A flat representation is a
unitary representation rho : Gamma -> U_K such that each rho(g_i) has every
K-th root of unity as eigenvalue, with multiplicity 1.

For a finite group, the flat representations are, up to conjugation, the
sums of irreducibles whose eigenvalue data on the generators form an exact
cover of the K x M grid (one eigenvalue slot per root of unity and per
generator).  This module computes:

  * the elements, conjugacy classes, power maps of Gamma,
  * the character table, numerically (Burnside's algorithm), rounded where
    only integers are used (dimensions, eigenvalue multiplicities, kernels),
  * all flat exact covers,
  * flat linearity: the irreducibles occurring in flat covers jointly
    separate the points of Gamma,
  * stationarity: the vector (K dim(rho)/|Gamma|)_rho is a convex
    combination of indicator vectors of flat covers; decided with an LP and
    certified exactly with rational arithmetic (a feasible point, or a
    Farkas certificate).

Only numpy and scipy are needed.  Python >= 3.8.
"""

import itertools
from fractions import Fraction

import numpy as np
from scipy.optimize import linprog


# ---------------------------------------------------------------------------
# finite permutation groups
# ---------------------------------------------------------------------------

class FiniteGroup:
    """Finite group generated by permutations of {0,...,n-1}.

    Product convention: (g*h)(x) = g(h(x)).
    """

    def __init__(self, gens, max_order=20000):
        gens = [tuple(int(a) for a in g) for g in gens]
        self.n = len(gens[0])
        ident = tuple(range(self.n))
        elems = [ident]
        index = {ident: 0}
        frontier = [ident]
        while frontier:
            new = []
            for x in frontier:
                for g in gens:
                    y = tuple(g[x[i]] for i in range(self.n))
                    if y not in index:
                        index[y] = len(elems)
                        elems.append(y)
                        new.append(y)
                        if len(elems) > max_order:
                            raise ValueError("group too large")
            frontier = new
        self.elems = elems
        self.index = index
        self.order = len(elems)
        self.gens = [index[g] for g in gens]
        E = np.array(elems, dtype=np.int64)
        self.E = E
        self._build_keys()
        self._build_table()
        self._build_classes()

    # fast lookup of permutations through the images of a base
    def _build_keys(self):
        E = self.E
        base = []
        for p in range(self.n):
            base.append(p)
            keys = np.zeros(self.order, dtype=np.int64)
            for b in base:
                keys = keys * self.n + E[:, b]
            if len(np.unique(keys)) == self.order:
                break
        self.base = base
        self.keys = keys
        self.sorter = np.argsort(keys)
        self.sorted_keys = keys[self.sorter]

    def lookup(self, P):
        """Indices of the permutations given as rows of P."""
        keys = np.zeros(P.shape[0], dtype=np.int64)
        for b in self.base:
            keys = keys * self.n + P[:, b]
        pos = np.searchsorted(self.sorted_keys, keys)
        return self.sorter[pos]

    def _build_table(self):
        E = self.E
        T = np.empty((self.order, self.order), dtype=np.int32)
        for i in range(self.order):
            T[i] = self.lookup(E[i][E])      # row i: e_i * e_j
        self.T = T
        ident = 0
        inv = np.empty(self.order, dtype=np.int64)
        rows, cols = np.nonzero(T == ident)
        inv[rows] = cols
        self.inv = inv

    def mul(self, a, b):
        return int(self.T[a, b])

    def power(self, a, m):
        r = 0
        for _ in range(m):
            r = self.mul(r, a)
        return r

    def elem_order(self, a):
        k, x = 1, a
        while x != 0:
            x = self.mul(x, a)
            k += 1
        return k

    def _build_classes(self):
        G = self.order
        cls = -np.ones(G, dtype=np.int64)
        classes = []
        allgens = list(range(G)) if G <= 64 else self.gens
        for a in range(G):
            if cls[a] >= 0:
                continue
            c = len(classes)
            orbit = [a]
            cls[a] = c
            k = 0
            while k < len(orbit):
                x = orbit[k]
                k += 1
                for g in allgens:
                    y = int(self.T[self.T[g, x], self.inv[g]])
                    if cls[y] < 0:
                        cls[y] = c
                        orbit.append(y)
            classes.append(orbit)
        self.cls = cls
        self.classes = classes
        self.nclasses = len(classes)
        self.class_sizes = np.array([len(c) for c in classes])
        self.reps = [c[0] for c in classes]

    def class_power(self, c, m):
        """Class of g^m, for g in class c."""
        return int(self.cls[self.power(self.reps[c], m)])


# ---------------------------------------------------------------------------
# character table (Burnside)
# ---------------------------------------------------------------------------

def character_table(G, seed=1):
    """Irreducible characters of G, as an array X[rho, class] (complex)."""
    r = G.nclasses
    cls = G.cls
    C = cls[G.T]                                  # class of e_i e_j
    N = np.zeros((r, r, r), dtype=np.int64)
    ci = np.repeat(cls, G.order)
    cj = np.tile(cls, G.order)
    np.add.at(N, (ci, cj, C.ravel()), 1)
    sizes = G.class_sizes
    a = N / sizes[None, None, :]                   # a[j,k,l] structure consts
    rng = np.random.default_rng(seed)
    coef = rng.normal(size=r) + 1j * rng.normal(size=r)
    A = np.tensordot(coef, a, axes=(0, 0))         # A[k,l]
    vals, vecs = np.linalg.eig(A)
    X = []
    for t in range(r):
        v = vecs[:, t]
        v = v / v[0]                               # class 0 = identity
        d2 = G.order / np.sum(np.abs(v) ** 2 / sizes)
        d = np.sqrt(d2.real)
        X.append(d * v / sizes)
    X = np.array(X)
    dims = np.rint(X[:, 0].real).astype(int)
    order = np.lexsort((np.round(-X.real.sum(axis=1), 6), dims))
    X, dims = X[order], dims[order]
    # sanity: orthogonality and sum of squares
    gram = (X * sizes) @ X.conj().T / G.order
    assert np.allclose(gram, np.eye(r), atol=1e-6), "character table failed"
    assert int(np.sum(dims ** 2)) == G.order
    return X, dims


def eigen_multiplicities(G, X, g, K):
    """For each irreducible, multiplicities of w^0,...,w^{K-1} as
    eigenvalues of rho(g), with w = exp(2 pi i / K); requires g^K = 1."""
    w = np.exp(2j * np.pi / K)
    pc = [G.class_power(int(G.cls[g]), m) for m in range(K)]
    out = []
    for row in X:
        mult = []
        for j in range(K):
            s = sum(row[pc[m]] * w ** (-j * m) for m in range(K)) / K
            mj = int(np.rint(s.real))
            assert abs(s - mj) < 1e-6
            mult.append(mj)
        out.append(mult)
    return np.array(out, dtype=int)


