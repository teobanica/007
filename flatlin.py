def extends_to_automorphism(G, images):
    """Does g_i -> images[i] extend to an automorphism of G?  Checked by
    building the graph of the map on all elements via words."""
    phi = {0: 0}
    frontier = [0]
    while frontier:
        new = []
        for x in frontier:
            for g, h in zip(G.gens, images):
                y = G.mul(g, x)
                z = G.mul(h, phi[x])
                if y in phi:
                    if phi[y] != z:
                        return False
                else:
                    phi[y] = z
                    new.append(y)
        frontier = new
    if len(set(phi.values())) != G.order:
        return False
    # homomorphism check on generators suffices with the word construction
    for x in range(G.order):
        for g, h in zip(G.gens, images):
            if phi[G.mul(x, g)] != G.mul(phi[x], h):
                return False
    return True


def exact_solve(A, b):
    """Solve A x = b exactly (Fractions); A has full column rank.
    Returns x or None if inconsistent."""
    m = len(A)
    n = len(A[0]) if m else 0
    M = [list(A[i]) + [b[i]] for i in range(m)]
    piv_cols = []
    row = 0
    for col in range(n):
        p = next((i for i in range(row, m) if M[i][col] != 0), None)
        if p is None:
            continue
        M[row], M[p] = M[p], M[row]
        pv = M[row][col]
        M[row] = [v / pv for v in M[row]]
        for i in range(m):
            if i != row and M[i][col] != 0:
                f = M[i][col]
                M[i] = [a - f * c for a, c in zip(M[i], M[row])]
        piv_cols.append(col)
        row += 1
    for i in range(row, m):
        if M[i][n] != 0:
            return None
    x = [Fraction(0)] * n
    for i, col in enumerate(piv_cols):
        x[col] = M[i][n]
    # verify
    for i in range(m):
        if sum(A[i][j] * x[j] for j in range(n)) != b[i]:
            return None
    return x


def perm_from_function(f, points):
    idx = {p: i for i, p in enumerate(points)}
    return tuple(idx[f(p)] for p in points)
